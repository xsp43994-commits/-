def mm_to_inches(mm: float) -> float:
    return mm / 25.4


def label_model(model: str) -> str:
    return MODEL_LABELS.get(model, model.replace("_", " ").title())


def style_axis(ax: plt.Axes) -> None:
    ax.grid(True, color="#E5E7EB", zorder=0)
    ax.spines[["top", "right"]].set_visible(False)
    ax.tick_params(length=3, width=0.6)


def panel_label(ax: plt.Axes, label: str) -> None:
    ax.text(-0.10, 1.05, label, transform=ax.transAxes, fontsize=10, fontweight="bold", va="top")


def save_figure(fig: plt.Figure, name: str, target: Path) -> list[dict]:
    target.mkdir(parents=True, exist_ok=True)
    records = []
    for extension in ("png", "pdf", "svg", "tiff"):
        path = target / f"{name}.{extension}"
        kwargs = {"bbox_inches": "tight", "pad_inches": 0.03}
        if extension in {"png", "tiff"}:
            kwargs["dpi"] = DPI
        fig.savefig(path, **kwargs)
        record = {"figure": name, "format": extension, "path": str(path), "bytes": path.stat().st_size, "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
        if extension in {"png", "tiff"}:
            with Image.open(path) as im:
                dpi_info = im.info.get("dpi")
                if isinstance(dpi_info, tuple):
                    dpi_info = [float(x) for x in dpi_info]
                record.update({"width_px": im.width, "height_px": im.height, "dpi": dpi_info})
        records.append(record)
    plt.close(fig)
    return records


