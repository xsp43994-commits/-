    ax.set_xticks(range(len(order)), [label_model(x) for x in order], rotation=30, ha="right")
    ax.set_ylabel("Safe priority-weighted coverage")
    ax.set_ylim(0.15, 0.66)
    ax.legend(handles=[Line2D([0], [0], marker="o", color="none", markeredgecolor="#334155", markerfacecolor="white", label="Unseen synthetic maps"), Line2D([0], [0], marker="^", color="none", markeredgecolor="#334155", markerfacecolor="white", label="Geographic DSM simulations")], frameon=False, loc="lower right")
