            x = i + offsets[domain] + rng.normal(0, 0.025, len(vals))
            ax.scatter(x, vals, s=12, marker=markers[domain], facecolors="white", edgecolors=COLORS.get(model, "#555555"), linewidths=0.7, alpha=0.9, zorder=3)
