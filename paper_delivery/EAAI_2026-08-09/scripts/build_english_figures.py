    records = []
    builders = {
        "Fig01_method": method_figure,
        "Fig02_coverage_priority": coverage_priority_figure,
        "Fig03_safety_resources": safety_resources_figure,
        "Fig04_time_tradeoff": time_tradeoff_figure,
        "Fig05_training": training_figure,
        "Fig06_transfer": transfer_figure,
        "Fig07_robustness": robustness_figure,
        "Fig08_ablation": ablation_figure,
    }
    for name, builder in builders.items():
        records.extend(save_figure(builder(), name, MAIN_DIR))
